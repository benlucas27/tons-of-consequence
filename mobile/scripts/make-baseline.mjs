// Writes (1) assets/feed-baseline.json: the feed as it is today, bundled so the first launch works offline, and
// (2) doors/*.js: one file per site data file, exporting each name from the feed. Run by `npm start` and by EAS builds.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const { buildFeed } = await import(pathToFileURL(join(root, 'src/lib/feed.js')).href);
const feed = buildFeed();
mkdirSync(join(here, '../assets'), { recursive: true });
mkdirSync(join(here, '../doors'), { recursive: true });
writeFileSync(join(here, '../assets/feed-baseline.json'), feed.json);

const data = JSON.parse(feed.json).data;
for (const [file, exports] of Object.entries(data)) {
  const lines = [`// Generated by scripts/make-baseline.mjs. Do not edit: data for ../src/data/${file}.js comes from the feed.`, "import { door } from '../src/feedStore';"];
  for (const name of Object.keys(exports)) lines.push(`export const ${name} = door('${file}', '${name}');`);
  if (file === 'name-aliases') lines.push('export const canonicalPlayer = (name) => NAME_ALIASES[name] || name;');
  writeFileSync(join(here, '../doors', `${file}.js`), lines.join('\n') + '\n');
}
console.log(`feed ${feed.version}: ${data.sample.SAMPLE_CENTURIES.length} hundreds, ${Object.keys(data).length} data doors written`);
